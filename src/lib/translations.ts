export function buildWhatsAppLink(
  phone: string,
  vehicleName: string = '',
  locationName: string = '',
  startDate: string = '',
  endDate: string = '',
  lang: Language = 'fr'
): string {
  const cleanPhone = phone.replace(/[^0-9]/g, '');
  let message = '';

  if (lang === 'ar') {
    if (vehicleName && locationName && startDate && endDate) {
      message = `مرحباً، أود استئجار سيارة ${vehicleName} في وكالة ${locationName} من ${startDate} إلى ${endDate}.`;
    } else if (vehicleName) {
      message = `مرحباً، أود الاستفسار عن كراء سيارة ${vehicleName} لدى سوبيكار.`;
    } else {
      message = `مرحباً، أود الاستفسار عن كراء سيارة لدى سوبيكار.`;
    }
  } else if (lang === 'en') {
    if (vehicleName && locationName && startDate && endDate) {
      message = `Hello, I would like to rent ${vehicleName} in ${locationName} from ${startDate} to ${endDate}.`;
    } else if (vehicleName) {
      message = `Hello, I would like to inquire about renting ${vehicleName} with SOUBAICAR.`;
    } else {
      message = `Hello, I would like to inquire about renting a car with SOUBAICAR.`;
    }
  } else {
    // fr default
    if (vehicleName && locationName && startDate && endDate) {
      message = `Bonjour, je souhaite louer ${vehicleName} à ${locationName} du ${startDate} au ${endDate}.`;
    } else if (vehicleName) {
      message = `Bonjour, je souhaite des informations pour louer la voiture ${vehicleName} chez SOUBAICAR.`;
    } else {
      message = `Bonjour, je souhaite des informations pour louer un véhicule chez SOUBAICAR.`;
    }
  }

  return `https://wa.me/${cleanPhone}?text=${encodeURIComponent(message)}`;
}

// Staff Transportation (B2B) route slug differs per locale, mirroring the
// existing vehicules/vehicles dual-slug convention used across the site.
export function getStaffTransportSlug(lang: Language): string {
  return lang === 'fr' ? 'transport-du-personnel' : 'staff-transportation';
}

export function getStaffTransportPath(lang: Language): string {
  return `/${lang}/${getStaffTransportSlug(lang)}`;
}
